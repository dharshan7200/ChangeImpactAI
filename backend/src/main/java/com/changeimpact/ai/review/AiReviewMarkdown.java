package com.changeimpact.ai.review;

import java.util.List;
import java.util.Map;

/**
 * Markdown section for a completed AI review, appended after the deterministic report. It is labelled as model output
 * and keeps each finding's validation status, so a reader of the export sees the same distinction as the UI.
 */
public final class AiReviewMarkdown {

    private AiReviewMarkdown() {}

    /** Empty string unless {@code review} (from {@link AiReviewService#latest}) is a completed review. */
    @SuppressWarnings("unchecked")
    public static String section(Map<String, Object> review) {
        if (review == null || !"COMPLETED".equals(review.get("status")) || !(review.get("result") instanceof Map<?, ?> raw)) return "";
        Map<String, Object> result = (Map<String, Object>) raw;
        StringBuilder md = new StringBuilder("\n## AI review (language model — check before acting)\n\n");
        md.append("_Generated by ").append(review.get("model")).append(" (prompt ").append(review.get("promptVersion"))
                .append(") from the evidence of this report. Each finding must cite that evidence; **verified** means every ")
                .append("citation exists and every code name it mentions exists in the evidence or the repository — not that ")
                .append("the reasoning is correct. The deterministic sections above are not changed by it._\n\n");
        if (result.get("summary") != null) md.append(oneLine(result.get("summary"))).append("\n\n");
        List<Map<String, Object>> findings = (List<Map<String, Object>>) result.getOrDefault("findings", List.of());
        if (!findings.isEmpty()) {
            md.append("| Severity | Finding | Validation | Cites |\n|---|---|---|---|\n");
            for (Map<String, Object> f : findings) {
                md.append("| ").append(f.get("severity")).append(" | **").append(cell(f.get("title"))).append("** ")
                        .append(cell(f.get("explanation"))).append(" | ")
                        .append("VERIFIED".equals(f.get("status")) ? "verified" : "unverified" + (f.get("reason") != null ? " (" + cell(f.get("reason")) + ")" : ""))
                        .append(" | ").append(String.join(", ", (List<String>) f.getOrDefault("citations", List.of()))).append(" |\n");
            }
            md.append('\n');
        }
        List<Map<String, Object>> tests = (List<Map<String, Object>>) result.getOrDefault("testSuggestions", List.of());
        if (!tests.isEmpty()) {
            md.append("**Suggested tests**\n\n");
            for (Map<String, Object> t : tests) md.append("- ").append(oneLine(t.get("title"))).append(" — ").append(oneLine(t.get("rationale"))).append('\n');
            md.append('\n');
        }
        List<String> questions = (List<String>) result.getOrDefault("questionsForAuthor", List.of());
        if (!questions.isEmpty()) {
            md.append("**Questions for the author**\n\n");
            for (String q : questions) md.append("- ").append(oneLine(q)).append('\n');
            md.append('\n');
        }
        return md.toString();
    }

    private static String oneLine(Object o) {
        return o == null ? "" : String.valueOf(o).replaceAll("\\s*\\n\\s*", " ").strip();
    }

    private static String cell(Object o) {
        return oneLine(o).replace("|", "\\|");
    }
}
