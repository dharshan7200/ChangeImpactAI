    static Map<String, Object> testView(TestRecommendation t) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("category", t.getCategory());
        m.put("priority", t.getPriority());
        if (t.getTestClass() != null) m.put("test", t.getTestClass() + "#" + t.getTestMethod());
        m.put("target", t.getTargetSymbol());
        m.put("reason", t.getReason());
        m.put("executionStatus", t.getExecutionStatus());
        if (t.getDepth() != null) m.put("depth", t.getDepth());
        return m;
    }

    static Map<String, Object> securityView(SecurityFinding f) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("severity", f.getSeverity());
        m.put("category", f.getCategory());
        m.put("source", f.getSource());
        m.put("ruleId", f.getRuleId());
        m.put("title", f.getTitle());
        m.put("message", f.getMessage());
        m.put("location", f.getFilePath() == null ? null : f.getFilePath() + (f.getStartLine() != null ? ":" + f.getStartLine() : ""));
        m.put("relation", f.getRelation());
        m.put("cwe", f.getCwe());
        return m;
    }

    static Map<String, Object> findingView(ImpactFinding f) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("affected", f.getAffectedQualifiedName());
        m.put("symbolType", f.getAffectedSymbolType());
        m.put("location", f.getFilePath() + ":" + f.getStartLine());
        m.put("impactType", f.getImpactType());
        m.put("evidence", f.getEvidence());
        m.put("depth", f.getDepth());
        m.put("strength", f.getStrength());
        m.put("alsoChanged", f.isAlsoChanged());
        m.put("path", f.getDependencyPath().stream().map(p -> p.get("simpleName")
                + (((List<?>) p.getOrDefault("relationship", List.of())).isEmpty() ? "" : " [" + String.join(",",
                ((List<?>) p.get("relationship")).stream().map(String::valueOf).toList()) + "]")).toList());
        return m;
    }

    private List<Map<String, Object>> architectureConcerns(ChangeAnalysis analysis, List<ChangedSymbol> symbols,
                                                          List<ImpactFinding> findings) {
        Set<String> touchedTypes = new HashSet<>();
        symbols.forEach(s -> touchedTypes.add(ownerType(s.getQualifiedName())));
        findings.stream().filter(f -> f.getDepth() == 1).forEach(f -> touchedTypes.add(ownerType(f.getAffectedQualifiedName())));
        List<Map<String, Object>> concerns = new ArrayList<>();
        architectureViolationRepository.findByRepositoryIdAndCommitSha(analysis.getRepositoryId(), analysis.getHeadCommit())
                .forEach(v -> {
                    String src = v.getSourceSymbol() != null ? ownerType(v.getSourceSymbol().getQualifiedName()) : null;
                    String tgt = v.getTargetSymbol() != null ? ownerType(v.getTargetSymbol().getQualifiedName()) : null;
                    if ((src != null && touchedTypes.contains(src)) || (tgt != null && touchedTypes.contains(tgt))) {
                        concerns.add(Map.of("rule", v.getRuleName(), "severity", v.getSeverity(),
                                "description", v.getDescription(),
                                "location", v.getSourceLocation() == null ? "" : v.getSourceLocation()));
                    }
                });
        return concerns;
    }

    private static List<Map<String, Object>> testsReferencingChanges(List<ImpactFinding> findings) {
        Map<String, Long> testClasses = findings.stream().filter(ImpactFinding::isTest)
                .collect(Collectors.groupingBy(f -> f.getAffectedOwnerType() != null ? f.getAffectedOwnerType()
                        : ownerType(f.getAffectedQualifiedName()), TreeMap::new, Collectors.counting()));
        return testClasses.entrySet().stream()
                .sorted(Map.Entry.<String, Long>comparingByValue().reversed())
                .map(e -> Map.<String, Object>of("testClass", e.getKey(), "references", e.getValue()))
                .toList();
    }

    /** Rule-based recommendations; each cites the findings that triggered it. */
    @SuppressWarnings("unchecked")
    List<Map<String, Object>> verificationSteps(ChangeAnalysis analysis, List<ChangedSymbol> symbols,
                                                Map<UUID, List<ImpactFinding>> bySymbol,
                                                List<TestRecommendation> tests, List<SecurityFinding> security) {
        List<Map<String, Object>> steps = new ArrayList<>();
        for (ChangedSymbol s : symbols) {
            if (s.isTest()) continue;
            Set<String> kinds = Set.of(s.getChangeKinds());
            List<ImpactFinding> direct = bySymbol.getOrDefault(s.getId(), List.of()).stream()
                    .filter(f -> f.getDepth() == 1 && !f.isTest()).toList();
            List<String> notUpdated = direct.stream().filter(f -> !f.isAlsoChanged())
                    .map(ImpactFinding::getAffectedQualifiedName).distinct().limit(8).toList();
            if (s.isBreaking() && !notUpdated.isEmpty()) {
                steps.add(step("HIGH", "Check " + notUpdated.size() + " direct dependent(s) of " + s.getSimpleName()
                                + " that were not modified in this change",
                        "Contract change (" + String.join(", ", kinds) + ") while dependents still reference the old contract",
                        notUpdated));
            }
            if (kinds.contains("REST_MAPPING_CHANGED")) {
                steps.add(step("HIGH", "Update API consumers and contract tests for " + s.getSimpleName(),
                        "HTTP endpoint mapping changed", List.of(String.valueOf(s.getDetails()))));
            }
            if (kinds.contains("SECURITY_RULE_CHANGED")) {
                steps.add(step("HIGH", "Re-run authorization tests and review access rules for " + s.getSimpleName(),
                        "Security annotation changed", List.of(s.getQualifiedName())));
            }
            if (kinds.contains("ENTITY_MAPPING_CHANGED")) {
                steps.add(step("MEDIUM", "Verify database schema/migrations and persistence tests for " + s.getSimpleName(),
                        "JPA mapping changed", List.of(s.getQualifiedName())));
            }
            if (kinds.contains("TRANSACTION_BOUNDARY_CHANGED")) {
                steps.add(step("MEDIUM", "Check transactional behaviour (rollback/propagation) around " + s.getSimpleName(),
                        "@Transactional changed", List.of(s.getQualifiedName())));
            }
            if (kinds.contains("CONFIGURATION_VALUE_CHANGED") && s.getDetails() != null) {
                steps.add(step("MEDIUM", "Verify configuration keys in every environment/profile for " + s.getSimpleName(),
                        "Bound configuration property changed",
                        (List<String>) s.getDetails().getOrDefault("configKeys", List.of())));
            }
            // Without Phase 5 test intelligence, fall back to static test references (Phase 3 rule)
            if (tests.isEmpty() && ("HIGH".equals(s.getRiskLevel()) || "CRITICAL".equals(s.getRiskLevel()))
                    && bySymbol.getOrDefault(s.getId(), List.of()).stream().noneMatch(ImpactFinding::isTest)) {
                steps.add(step("MEDIUM", "Add or identify tests covering " + s.getSimpleName(),
                        s.getRiskLevel() + " risk and no test code references it (static analysis)", List.of(s.getQualifiedName())));
            }
        }
        Map<String, Object> summary = analysis.getSummary() != null ? analysis.getSummary() : Map.of();
        if (Boolean.TRUE.equals(summary.get("buildFilesChanged"))) {
            steps.add(step("HIGH", "Run the full test suite", "Build/dependency files changed; static impact analysis cannot "
                    + "see library behaviour changes", List.of()));
        }
        List<TestRecommendation> selected = tests.stream()
                .filter(t -> "DIRECT".equals(t.getCategory()) || "INDIRECT".equals(t.getCategory())).toList();
        if (!selected.isEmpty()) {
            List<String> failed = selected.stream().filter(t -> "FAILED".equals(t.getExecutionStatus()))
                    .map(t -> t.getTestClass() + "#" + t.getTestMethod()).limit(20).toList();
            if (!failed.isEmpty()) {
                steps.add(step("HIGH", "Fix " + failed.size() + " failing selected test(s)",
                        "Uploaded JUnit results of the head commit report them as failed", failed));
            }
            long classes = selected.stream().map(TestRecommendation::getTestClass).distinct().count();
            steps.add(step(selected.stream().anyMatch(t -> "HIGH".equals(t.getPriority())) ? "HIGH" : "MEDIUM",
                    "Run the " + selected.size() + " selected test method(s) in " + classes + " class(es)",
                    "Test methods that reach the changed code through the dependency graph (static selection)",
                    selected.stream().map(t -> t.getTestClass() + "#" + t.getTestMethod()).limit(20).toList()));
        } else {
            List<String> testClasses = bySymbol.values().stream().flatMap(List::stream).filter(ImpactFinding::isTest)
                    .map(f -> f.getAffectedOwnerType() != null ? f.getAffectedOwnerType() : f.getAffectedQualifiedName())
                    .distinct().sorted().limit(20).toList();
            if (!testClasses.isEmpty()) {
                steps.add(step("MEDIUM", "Run the " + testClasses.size() + " test class(es) that reference changed code",
                        "Found by reverse dependency traversal", testClasses));
            }
        }
        List<String> gaps = tests.stream().filter(t -> "MISSING_TEST".equals(t.getCategory()) && "HIGH".equals(t.getPriority()))
                .map(TestRecommendation::getTargetSymbol).limit(10).toList();
        if (!gaps.isEmpty()) {
            steps.add(step("HIGH", "Add tests for " + gaps.size() + " high-risk changed symbol(s) that no test reaches",
                    "No test method reaches them through the dependency graph", gaps));
        }
        List<String> severe = security.stream().filter(f -> severityRank(f.getSeverity()) <= 1)
                .map(f -> f.getTitle() + (f.getFilePath() != null ? " (" + f.getFilePath() + (f.getStartLine() != null ? ":" + f.getStartLine() : "") + ")" : ""))
                .limit(10).toList();
        if (!severe.isEmpty()) {
            steps.add(step("HIGH", "Security review of " + severe.size() + " high/critical finding(s)",
                    "Security-sensitive code, Semgrep matches or vulnerable dependencies in this change", severe));
        }
        steps.sort(Comparator.comparing(m -> "HIGH".equals(m.get("priority")) ? 0 : 1));
        return steps;
    }

    private static Map<String, Object> step(String priority, String action, String reason, List<String> evidence) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("priority", priority);
        m.put("action", action);
        m.put("reason", reason);
        m.put("evidence", evidence);
        return m;
    }

    private Map<String, Object> commitInfo(UUID repositoryId, String ref, String sha) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("ref", ref);
        m.put("sha", sha);
        if (sha != null) {
            commitRepository.findByRepositoryIdAndSha(repositoryId, sha).ifPresent((Commit c) -> {
                m.put("message", c.getMessage() == null ? null : c.getMessage().lines().findFirst().orElse(""));
                m.put("author", c.getAuthorName());
                m.put("date", c.getCommitDate());
            });
        }
        return m;
    }

    static String ownerType(String qualifiedName) {
        int hash = qualifiedName.indexOf('#');
        return hash > 0 ? qualifiedName.substring(0, hash) : qualifiedName;
    }

