    @SuppressWarnings("unchecked")
    public String toMarkdown(Map<String, Object> report) {
        StringBuilder md = new StringBuilder();
        Map<String, Object> base = (Map<String, Object>) report.get("base");
        Map<String, Object> head = (Map<String, Object>) report.get("head");
        Map<String, Object> summary = (Map<String, Object>) report.getOrDefault("summary", Map.of());
        md.append("# ChangeImpact AI report: ").append(report.get("repository")).append("\n\n");
        md.append("**").append(shortSha(base.get("sha"))).append(" → ").append(shortSha(head.get("sha"))).append("**")
                .append(" · Risk: **").append(report.get("riskLevel")).append("** (").append(report.get("riskScore")).append("/100)\n\n");
        if (summary != null && !summary.isEmpty()) {
            md.append("| Files changed | Symbols changed | Breaking | Directly impacted | Total impacted | Tests referencing |\n");
            md.append("|---|---|---|---|---|---|\n");
            md.append("| ").append(summary.get("filesChanged")).append(" | ").append(summary.get("productionSymbolsChanged"))
                    .append(" | ").append(summary.get("breakingChanges")).append(" | ").append(summary.get("directlyImpacted"))
                    .append(" | ").append(summary.get("totalImpacted")).append(" | ").append(summary.get("impactedTests")).append(" |\n\n");
        }
        List<Map<String, Object>> checklist = (List<Map<String, Object>>) report.getOrDefault("checklist", List.of());
        if (!checklist.isEmpty()) {
            md.append("## Pre-merge checklist\n\n");
            checklist.forEach(c -> {
                md.append("- [ ] ").append(c.get("action"));
                List<?> ev = (List<?>) c.getOrDefault("evidence", List.of());
                if (!ev.isEmpty()) md.append(" — ").append(ev.stream().map(e -> "`" + escape(String.valueOf(e)) + "`").collect(Collectors.joining(", ")));
                if (c.get("moreEvidence") != null) md.append(" …and ").append(c.get("moreEvidence")).append(" more");
                md.append('\n');
            });
            md.append('\n');
        }
        if (report.get("reviewers") instanceof Map<?, ?> rv && rv.get("suggestions") instanceof List<?> sugg && !sugg.isEmpty()) {
            md.append("## Suggested reviewers\n\n| Reviewer | Why |\n|---|---|\n");
            sugg.forEach(o -> {
                Map<?, ?> s = (Map<?, ?>) o;
                List<?> ev = s.get("evidence") instanceof List<?> l ? l : List.of();
                String why = ev.stream().limit(3).map(e -> {
                    Map<?, ?> f = (Map<?, ?>) e;
                    String p = String.valueOf(f.get("path"));
                    int commits = ((Number) f.get("commits")).intValue();
                    return p.substring(p.lastIndexOf('/') + 1) + " (" + commits + (commits == 1 ? " commit, " : " commits, ")
                            + Math.round(((Number) f.get("share")).doubleValue() * 100) + "% of its history"
                            + ("IMPACTED".equals(f.get("relation")) ? ", impacted" : "") + ")";
                }).collect(Collectors.joining("; "));
                md.append("| ").append(escape(String.valueOf(s.get("name")))).append(" | ").append(escape(why)).append(" |\n");
            });
            md.append("\n_From recency-weighted file ownership in the history before this change; authors of the change are excluded._\n\n");
        }
        if (report.get("architecture") instanceof Map<?, ?> ar && "OK".equals(ar.get("status")) && ar.get("findings") instanceof List<?> af) {
            md.append("## Architecture drift\n\n");
            af.forEach(f -> md.append("- ").append(escape(String.valueOf(f))).append('\n'));
            md.append('\n');
        }
        if (report.get("defectModel") instanceof Map<?, ?> dm && "ACCEPTED".equals(dm.get("status"))
                && dm.get("commits") instanceof List<?> dc && !dc.isEmpty()) {
            md.append("## History-based defect estimate (experimental)\n\n| Commit | Estimate | Raised by |\n|---|---|---|\n");
            dc.stream().limit(5).forEach(o -> {
                Map<?, ?> c = (Map<?, ?>) o;
                String drivers = c.get("drivers") instanceof List<?> dr ? dr.stream()
                        .filter(d -> ((Number) ((Map<?, ?>) d).get("contribution")).doubleValue() > 0).limit(3)
                        .map(d -> String.valueOf(((Map<?, ?>) d).get("feature"))).collect(Collectors.joining(", ")) : "";
                if (drivers.isEmpty()) drivers = "—";
                md.append("| `").append(String.valueOf(c.get("sha")), 0, 7).append("` ").append(escape(String.valueOf(c.get("message"))))
                        .append(" | ").append(String.format(Locale.ROOT, "%.0f %%", 100 * ((Number) c.get("probability")).doubleValue()))
                        .append(" | ").append(drivers).append(" |\n");
            });
            md.append(String.format(Locale.ROOT, "%n_Logistic model trained on this repository's history (bug-introducing commits found by SZZ "
                    + "from bug-fix messages; test ROC-AUC %.2f on later commits). An estimate from past patterns, not a finding about this code._%n%n",
                    ((Number) dm.get("testAuc")).doubleValue()));
        }
        List<Map<String, Object>> steps = (List<Map<String, Object>>) report.getOrDefault("verificationSteps", List.of());
        if (!steps.isEmpty()) {
            md.append("## Recommended verification\n\n");
            steps.forEach(s -> md.append("- **").append(s.get("priority")).append("** ").append(s.get("action"))
                    .append(" — ").append(s.get("reason")).append('\n'));
            md.append('\n');
        }
        Map<String, Object> testSection = (Map<String, Object>) report.get("tests");
        if (testSection != null) {
            List<Map<String, Object>> selected = (List<Map<String, Object>>) testSection.getOrDefault("selected", List.of());
            List<Map<String, Object>> missing = (List<Map<String, Object>>) testSection.getOrDefault("missingTests", List.of());
            md.append("## Tests\n\n");
            Map<String, Object> ts = testSection.get("summary") instanceof Map<?, ?> m ? (Map<String, Object>) m : Map.of();
            if (ts.get("changedLineCoverage") instanceof Map<?, ?> cv) {
                md.append("Changed-line coverage (JaCoCo, head commit): **").append(cv.get("changedLinesCovered")).append('/')
                        .append(cv.get("changedLinesExecutable")).append("**").append(cv.get("ratio") != null ? " (" + cv.get("ratio") + "%)" : "").append("\n\n");
            }
            if (ts.get("mutation") instanceof Map<?, ?> mu && "AVAILABLE".equals(mu.get("status")) && mu.get("mutationScore") != null) {
                md.append("Mutation score of changed methods (PIT): **").append(mu.get("mutationScore")).append("%**, ")
                        .append(mu.get("weakMethods")).append(" method(s) below 70%\n\n");
                if (mu.get("methods") instanceof List<?> methods) {
                    methods.stream().filter(o -> o instanceof Map<?, ?> mm && mm.get("mutationScore") instanceof Number n && n.doubleValue() < 70)
                            .limit(5).forEach(o -> {
                                Map<?, ?> mm = (Map<?, ?>) o;
                                Map<?, ?> st = mm.get("byStatus") instanceof Map<?, ?> b ? b : Map.of();
                                md.append("- `").append(shortSymbol(String.valueOf(mm.get("symbol")))).append("` ")
                                        .append(mm.get("mutationScore")).append("% — ")
                                        .append(st.get("SURVIVED") == null ? 0 : st.get("SURVIVED")).append(" survived, ")
                                        .append(st.get("NO_COVERAGE") == null ? 0 : st.get("NO_COVERAGE")).append(" not covered of ")
                                        .append(mm.get("mutants")).append(" mutants\n");
                            });
                    md.append('\n');
                }
            }
            if (!selected.isEmpty()) {
                md.append("**").append(selected.size()).append(" test method(s) reach the changed code**\n\n");
                md.append("| Priority | Test | Kind | Last result | Hops |\n|---|---|---|---|---|\n");
                selected.stream().limit(25).forEach(t -> md.append("| ").append(t.get("priority")).append(" | `")
                        .append(shortSymbol(String.valueOf(t.get("test")))).append("` | ").append(t.get("category")).append(" | ")
                        .append(t.get("executionStatus")).append(" | ").append(t.get("depth") == null ? "" : t.get("depth")).append(" |\n"));
                if (selected.size() > 25) md.append("\n…and ").append(selected.size() - 25).append(" more (see the full report)\n");
                md.append('\n');
            } else {
                md.append("No test method reaches the changed code through the dependency graph.\n\n");
            }
            if (!missing.isEmpty()) {
                md.append("**Changed code without a reaching test:**\n\n");
                missing.stream().limit(15).forEach(t -> md.append("- ").append(t.get("priority")).append(" `")
                        .append(shortSymbol(String.valueOf(t.get("target")))).append("` — ").append(t.get("reason")).append('\n'));
                md.append('\n');
            }
        }
        Map<String, Object> securitySection = (Map<String, Object>) report.get("security");
        if (securitySection != null) {
            List<Map<String, Object>> sec = (List<Map<String, Object>>) securitySection.getOrDefault("findings", List.of());
            md.append("## Security\n\n");
            if (sec.isEmpty()) {
                md.append("No security-relevant findings for this change.\n\n");
            } else {
                md.append("| Severity | Finding | Source | Location |\n|---|---|---|---|\n");
                sec.stream().limit(30).forEach(f -> md.append("| ").append(f.get("severity")).append(" | ")
                        .append(escape(String.valueOf(f.get("title")))).append(" | ").append(f.get("source")).append(" | ")
                        .append(f.get("location") == null ? "" : f.get("location")).append(" |\n"));
                md.append('\n');
            }
            if (securitySection.get("summary") instanceof Map<?, ?> ss && ss.get("semgrep") instanceof Map<?, ?> sg
                    && !"COMPLETED".equals(sg.get("status"))) {
                md.append("_Semgrep: ").append(sg.get("status")).append(sg.get("detail") != null ? " — " + sg.get("detail") : "").append("_\n\n");
            }
        }
        List<Map<String, Object>> changed = (List<Map<String, Object>>) report.getOrDefault("changedSymbols", List.of());
        if (!changed.isEmpty()) {
            md.append("## Changed symbols\n\n| Risk | Symbol | Change | Direct | Indirect | Location |\n|---|---|---|---|---|---|\n");
            changed.stream().limit(50).forEach(c -> md.append("| ").append(c.get("riskLevel")).append(' ').append(c.get("riskScore"))
                    .append(" | `").append(c.get("qualifiedName")).append("` | ").append(String.join(", ", (String[]) c.get("changeKinds")))
                    .append(Boolean.TRUE.equals(c.get("breaking")) ? " ⚠️" : "").append(" | ").append(c.get("directImpacts"))
                    .append(" | ").append(c.get("indirectImpacts")).append(" | ").append(c.get("location")).append(" |\n"));
            md.append('\n');
        }
        md.append("> ").append(DISCLAIMER).append('\n');
        return md.toString();
    }

    /** {@code a.b.Outer$Inner#m(X,Y)} → {@code Outer.Inner#m(…)}; keeps a type's simple name otherwise. */
    static String shortSymbol(String qualifiedName) {
        int hash = qualifiedName.indexOf('#');
        String type = hash > 0 ? qualifiedName.substring(0, hash) : qualifiedName;
        int dollar = type.indexOf('$');
        String outer = dollar > 0 ? type.substring(0, dollar) : type;
        String simple = outer.substring(outer.lastIndexOf('.') + 1) + (dollar > 0 ? "." + type.substring(dollar + 1).replace('$', '.') : "");
        if (hash < 0) return simple;
        String member = qualifiedName.substring(hash + 1);
        int paren = member.indexOf('(');
        if (paren >= 0 && member.length() > paren + 2) member = member.substring(0, paren) + "(…)";
        return simple + "#" + member;
    }

    private static String escape(String v) {
        return v.replace("|", "\\|").replace("\n", " ");
    }

    private static String shortSha(Object sha) {
        String s = String.valueOf(sha);
        return s.length() > 7 ? s.substring(0, 7) : s;
    }
